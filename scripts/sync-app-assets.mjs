// Copies the protocol, LOOPS.md, VOICE.md and brand files into app/, so the one-click
// template stays self-contained (the Deploy button clones only app/).
import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const app = join(root, "app");
const kit = join(root, "memory-bank", "onhundred-logo-kit");

const docs = {
  protocol: ["Onhundred Protocol v1.0.md", "protocol.md"],
  loops: ["LOOPS.md", "LOOPS.md"],
  voice: ["VOICE.md", "VOICE.md"],
};
const brand = [
  ["svg/favicon.svg", "favicon.svg"],
  ["favicon.ico", "favicon.ico"],
  ["png/on100-dark-180.png", "apple-touch-icon.png"],
  ["png/onhundred-wordmark-dark-1200.png", "wordmark.png"],
];

await mkdir(join(app, "docs"), { recursive: true });
await mkdir(join(app, "public"), { recursive: true });

const texts = {};
for (const [key, [from, to]] of Object.entries(docs)) {
  const text = await readFile(join(root, "memory-bank", from), "utf8");
  await writeFile(join(app, "docs", to), text);
  texts[key] = text;
}
await writeFile(
  join(app, "src", "docs.mjs"),
  "// Generated by scripts/sync-app-assets.mjs. Do not edit; edit memory-bank/ and run npm run sync-app.\n" +
    Object.entries(texts)
      .map(([k, v]) => `export const ${k} = ${JSON.stringify(v)};`)
      .join("\n") +
    "\n"
);
for (const [from, to] of brand) await copyFile(join(kit, from), join(app, "public", to));

console.log("synced app/docs, app/src/docs.mjs and app/public brand files");
